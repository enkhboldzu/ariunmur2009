const WORD_BANK = wordbank

function getExtensions(word) {
  const head = clean(word)
  const chars = [...head]
  const picked = []
  const seen = new Set([head])

  const take = (cands) => {
    for (const [w, freq] of cands) {
      if (seen.has(w)) continue
      if ([...w].length > 4) continue
      if (w.length < head.length) continue
      seen.add(w)
      picked.push(w)
      if (picked.length >= 4) return
    }
  }

  const matches = []
  for (const [w, freq] of WORD_BANK) {
    if (w === head) continue
    if (w.includes(head)) matches.push([w, freq])
  }
  take(matches)

  if (picked.length < 3 && head.length === 1) {
    const charMatches = []
    for (const [w, freq] of WORD_BANK) {
      if (w === head) continue
      if (w.length >= 2 && w.length <= 3 && w.includes(head)) charMatches.push([w, freq])
    }
    take(charMatches)
  }

  if (picked.length < 3) {
    const first = chars[0]
    const firstMatches = []
    for (const [w, freq] of WORD_BANK) {
      if (w === head) continue
      if ([...w][0] === first && w.length <= 3) firstMatches.push([w, freq])
    }
    take(firstMatches)
  }

  return picked.slice(0, 4)
}

const uniq = (arr) => [...new Set(arr)]

function generate(word) {
  const posInfo = posData[clean(word.simplified)] || ['名词', 'Нэр үг']
  const pos = posInfo[0].replace(/[\/（）]/g, '')
  const w = clean(word.simplified)

  const extensions = getExtensions(word.simplified)

  const collTmpl = (COLLOCATION_TEMPLATES[pos] || (() => []))(w)
  const singleChar = w.length === 1
  let collocations = singleChar
    ? uniq([...extensions.slice(0, 2), ...collTmpl]).slice(0, 3)
    : uniq([...collTmpl, ...extensions.slice(0, 1)]).slice(0, 3)
  if (!collocations.length) collocations = [`${w}的`, `${w}很${singleChar ? '多' : '好'}`]

  const sentences = (SENTENCE_TEMPLATES[pos] || (() => []))(w).slice(0, 2)
  const realSentences = sentences.filter((s) => s.includes(w))

  return {
    pos: posInfo[0],
    pos_mn: posInfo[1],
    collocations,
    sentences: realSentences.length ? realSentences : [`我喜欢${w}。`],
    extensions,
  }
}

