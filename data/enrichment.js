const normKey = (k) => k.replace(/\s+/g, '')
const buildIndex = (obj) => {
  const idx = {}
  for (const [k, v] of Object.entries(obj)) idx[normKey(k)] = v
  return idx
}
const CURATED_INDEX = buildIndex(CURATED)
const POS_MISSING_INDEX = buildIndex(POS_MISSING)

function getEnrichment(word) {
  const key = normKey(`${word.simplified} ${word.pinyin}`)
  const curated = CURATED_INDEX[key] || POS_MISSING_INDEX[key]
  if (curated) {
    return {
      pos: curated[0],
      pos_mn: curated[1],
      collocations: curated[2],
      sentences: curated[3],
      extensions: curated[4],
    }
  }
  return generate(word)
}

module.exports = { getEnrichment }
